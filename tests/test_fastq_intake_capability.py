class BoundedReader:
    """A non-seekable synthetic binary stream with observable consumption."""

    def __init__(self, data, *, short_read=None, offset=0, on_first_read=None):
        self.data = data
        self.position = offset
        self.short_read = short_read
        self.on_first_read = on_first_read
        self.requests = []
        self.eof_observed = False
        self.closed = False

    def read(self, size):
        if type(size) is not int or not 1 <= size <= MAX_READ:
            raise AssertionError("A bounded positive read size is required")
        self.requests.append(size)
        if self.on_first_read is not None:
            callback, self.on_first_read = self.on_first_read, None
            callback()
        if self.short_read is not None:
            size = min(size, self.short_read)
        end = min(self.position + size, len(self.data))
        chunk = self.data[self.position:end]
        self.position = end
        if not chunk:
            self.eof_observed = True
        return chunk

    def seek(self, *args):
        raise AssertionError("The supplied stream must not be repositioned")

    def close(self):
        self.closed = True
        raise AssertionError("The supplied stream must not be closed")


class NoRead:
    def __init__(self):
        self.calls = 0

    def read(self, size):
        self.calls += 1
        raise AssertionError("Invalid declarations must be refused before I/O")


def call_validator(r1, r2, profile):
    # Keep schema and synthetic-case construction usable before implementation.
    from omnigenis.capabilities.fastq_intake import validate_paired_fastq
    return validate_paired_fastq(r1, r2, profile)


class FastqIntakeTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.input_schema = json.loads(
            (ROOT / "schemas" / "fastq-input-profile.v1.schema.json").read_text()
        )
        cls.result_schema = json.loads(
            (ROOT / "schemas" / "fastq-intake-result.v1.schema.json").read_text()
        )
        Draft202012Validator.check_schema(cls.input_schema)
        Draft202012Validator.check_schema(cls.result_schema)
        cls.input_validator = Draft202012Validator(cls.input_schema)
        cls.result_validator = Draft202012Validator(cls.result_schema)

    def assert_result(self, result):
        exported = result.to_dict()
        self.result_validator.validate(exported)
        self.assertLessEqual(len(canonical_bytes(exported)), 16384)
        self.assertEqual(set(exported["provenance_refs"]), SOURCE_URLS)
        self.assertEqual(exported["raw_artifact_refs"], [])
        return exported

    def assert_valid(self, result, profile, r1, r2, pair_count=2):
        self.assertIs(result.is_valid, True)
        exported = self.assert_result(result)
        self.assertEqual(exported["canonical_status"], "VALID")
        payload = exported["canonical_payload"]
        self.assertEqual(payload["diagnostics"], [])
        accepted = payload["accepted_pair"]
        self.assertEqual(
            accepted["input_profile_sha256"],
            hashlib.sha256(canonical_bytes(profile)).hexdigest(),
        )
        self.assertEqual(accepted["pair_count"], pair_count)
        self.assertEqual(accepted["assessments"], ASSESSMENTS)
        for name, data in (("r1", r1), ("r2", r2)):
            self.assertEqual(accepted[name], {
                "content_sha256": hashlib.sha256(data).hexdigest(),
                "size_bytes": len(data),
            })
        return exported

    def assert_refused(self, result, codes, *, mate=None, record_index=None):
        self.assertIs(result.is_valid, False)
        exported = self.assert_result(result)
        self.assertEqual(exported["canonical_status"], "INVALID")
        payload = exported["canonical_payload"]
        self.assertIsNone(payload["accepted_pair"])
        self.assertEqual(len(payload["diagnostics"]), 1)
        diagnostic = payload["diagnostics"][0]
        self.assertEqual(set(diagnostic), {"code", "mate", "record_index"})
        self.assertIn(diagnostic["code"], set(codes))
        if mate is not None:
            self.assertEqual(diagnostic["mate"], mate)
        if record_index is not None:
            self.assertEqual(diagnostic["record_index"], record_index)
        return exported

