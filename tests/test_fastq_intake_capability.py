def canonical_bytes(value):
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=True,
        allow_nan=False,
    ).encode("utf-8")


def load_fixture_pair():
    return (
        (FIXTURES / "valid-r1.fastq").read_bytes(),
        (FIXTURES / "valid-r2.fastq").read_bytes(),
    )


def bound_profile(r1, r2):
    """Bind independently generated bytes without using the implementation."""
    profile = json.loads((FIXTURES / "valid-input-profile.json").read_text())
    for name, data in (("r1", r1), ("r2", r2)):
        profile[name]["content_sha256"] = hashlib.sha256(data).hexdigest()
        profile[name]["size_bytes"] = len(data)
    return profile


def make_record(
    read=1, sequence=b"ACGTN", quality=None, *, instrument="SYNTHSEQ-01",
    run="0007", flowcell="FLOWCELL-01", lane="01", tile="1101",
    x="10", y="20", filtered="N", control="0", index="ACGT+TGCA",
    separator=b"+", eol=b"\n",
):
    if quality is None:
        quality = b"I" * len(sequence)
    header = (
        f"@{instrument}:{run}:{flowcell}:{lane}:{tile}:{x}:{y} "
        f"{read}:{filtered}:{control}:{index}"
    ).encode("ascii")
    return eol.join((header, sequence, separator, quality)) + eol


def replace_line(data, index, replacement):
    lines = data.split(b"\n")
    lines[index] = replacement
    return b"\n".join(lines)


